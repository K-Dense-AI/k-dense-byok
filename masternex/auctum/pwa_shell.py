if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(description="Generate PWA shell files for a MASTERNEX platform")
    parser.add_argument(
        "--platform",
        choices=list(PLATFORM_PRESETS.keys()),
        default="auctum.atlas",
        help="Target platform",
    )
    parser.add_argument("--output-dir", default=None, help="Override output directory")
    parser.add_argument("--all", action="store_true", help="Build shells for all platforms")
    args = parser.parse_args()

    platforms = list(PLATFORM_PRESETS.keys()) if args.all else [args.platform]
    for plat in platforms:
        paths = build_pwa_shell(plat, output_dir=args.output_dir)
        print(f"\n{plat}:")
        for name, path in paths.items():
            size = path.stat().st_size
            print(f"  {path}  ({size:,} bytes)")
