@dataclass
class PwaConfig:
    """Per-platform PWA shell configuration."""

    # Platform identity
    platform: str = "auctum.atlas"            # "auctum.atlas" | "luminaac-ultimate"
    app_name: str = "Auctum Atlas"
    app_short_name: str = "Atlas"
    description: str = "Auctum Atlas – AI-driven property intelligence platform"
    theme_color: str = "#0a1628"              # Auctum navy
    background_color: str = "#0a1628"
    display: str = "standalone"
    start_url: str = "/"
    scope: str = "/"

    # Cache versioning — bump on any app-shell change
    cache_version: str = "v1.0.0"
    model_cache_name: str = "masternex-models-v1"
    api_cache_name: str = "masternex-api-v1"

    # App shell assets precached on SW install
    app_shell_assets: List[str] = field(default_factory=lambda: [
        "/",
        "/index.html",
        "/static/js/main.js",
        "/static/css/main.css",
        "/static/fonts/inter-var.woff2",
        "/offline.html",
    ])

    # Path to wasm_manifest.json (generated by wasm_export.py)
    wasm_manifest_url: str = "/dist/wasm/wasm_manifest.json"

    # Icons for PWA install prompt (must be present in /static/icons/)
    icons: List[Dict] = field(default_factory=lambda: [
        {"src": "/static/icons/icon-192.png", "sizes": "192x192", "type": "image/png"},
        {"src": "/static/icons/icon-512.png", "sizes": "512x512", "type": "image/png"},
        {"src": "/static/icons/icon-512-maskable.png", "sizes": "512x512",
         "type": "image/png", "purpose": "maskable"},
    ])

    # App shortcuts (shown in mobile long-press / Windows JumpList)
    shortcuts: List[Dict] = field(default_factory=list)

    # API route prefix (Network-First strategy)
    api_prefix: str = "/api/"

    # AG-UI streaming route (never cached)
    agui_prefix: str = "/agui/"

    # Network-first timeout (ms) before falling back to cache
    network_timeout_ms: int = 5000

    # Output directory
    output_dir: str = "dist/pwa"


