def make_config(platform: str) -> PwaConfig:
    """Build a PwaConfig from a platform preset."""
    cfg = PwaConfig(platform=platform)
    preset = PLATFORM_PRESETS.get(platform, {})
    for key, val in preset.items():
        setattr(cfg, key, val)
    cfg.output_dir = f"dist/pwa/{platform}"
    return cfg


