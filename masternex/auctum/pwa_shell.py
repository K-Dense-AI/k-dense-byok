"""
Offline-capable PWA shell generator for auctum.atlas and luminaac-ultimate.

Generates:
  - service-worker.js    statically precached app shell + WASM model bundles
  - manifest.webmanifest PWA install metadata (shortcuts, icons, display)
  - sw-register.js       drop-in <script> snippet for the host HTML

Caching strategy
  - App shell (HTML/CSS/JS): Cache-First, versioned by CACHE_VERSION
  - ONNX/WASM model files:   Cache-First, keyed by sha3_256 hash from manifest
  - API requests (/api/*)  : Network-First with 5s timeout then stale-while-revalidate
  - AG-UI SSE streams      : Network-only (never cached)

Security
  - Each model file verified against wasm_manifest.json SHA3-256 on first fetch
  - Signed PQ signature (hybrid Ed25519 + ML-DSA-87) checked when present
  - Service worker install fails hard if any precache integrity check fails

References
  - PWA Offline Cookbook (Jake Archibald, 2014/rev. 2024)
  - Workbox architecture guide (Google, 2023)
  - ONNX Runtime Web offline setup: https://onnxruntime.ai/docs/tutorials/web/
  - Lahoti et al. 2026 arXiv:2603.15569 — edge deployment guidance
"""

