def build_pwa_shell(
    platform: str = "auctum.atlas",
    output_dir: Optional[str] = None,
    cfg: Optional[PwaConfig] = None,
) -> Dict[str, Path]:
    """Generate all PWA shell files for the given platform.

    Returns a dict of {filename: Path} for the generated files.

    Example:
        paths = build_pwa_shell("luminaac-ultimate")
        # → dist/pwa/luminaac-ultimate/service-worker.js
        #   dist/pwa/luminaac-ultimate/manifest.webmanifest
        #   dist/pwa/luminaac-ultimate/sw-register.html
        #   dist/pwa/luminaac-ultimate/offline.html
    """
    if cfg is None:
        cfg = make_config(platform)
    if output_dir:
        cfg.output_dir = output_dir

    out = Path(cfg.output_dir)
    out.mkdir(parents=True, exist_ok=True)

    generated: Dict[str, Path] = {}

    sw_path = out / "service-worker.js"
    sw_path.write_text(generate_service_worker(cfg), encoding="utf-8")
    generated["service-worker.js"] = sw_path

    manifest_path = out / "manifest.webmanifest"
    manifest_path.write_text(generate_manifest(cfg), encoding="utf-8")
    generated["manifest.webmanifest"] = manifest_path

    register_path = out / "sw-register.html"
    register_path.write_text(generate_register_snippet(cfg), encoding="utf-8")
    generated["sw-register.html"] = register_path

    offline_path = out / "offline.html"
    offline_path.write_text(generate_offline_page(cfg), encoding="utf-8")
    generated["offline.html"] = offline_path

    # Write a build manifest so CI can verify freshness
    build_meta = {
        "platform": cfg.platform,
        "cache_version": cfg.cache_version,
        "app_shell_count": len(cfg.app_shell_assets),
        "files": {k: str(v) for k, v in generated.items()},
        "sha256": {
            k: hashlib.sha256(v.read_bytes()).hexdigest()
            for k, v in generated.items()
        },
    }
    meta_path = out / "pwa-build-meta.json"
    meta_path.write_text(json.dumps(build_meta, indent=2), encoding="utf-8")
    generated["pwa-build-meta.json"] = meta_path

    return generated


