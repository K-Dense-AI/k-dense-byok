def generate_register_snippet(cfg: PwaConfig) -> str:
    """Return a drop-in <script> snippet for the host HTML <head>."""
    return textwrap.dedent(f"""\
    <!-- sw-register.js — auto-generated by masternex/edge/pwa_shell.py -->
    <script>
    (function() {{
      if (!("serviceWorker" in navigator)) return;
      window.addEventListener("load", function() {{
        navigator.serviceWorker.register("/service-worker.js", {{ scope: "{cfg.scope}" }})
          .then(function(reg) {{
            console.log("[{cfg.app_name}] Service worker registered:", reg.scope);
            // Listen for SW updates and prompt user to refresh
            reg.addEventListener("updatefound", function() {{
              const newWorker = reg.installing;
              newWorker.addEventListener("statechange", function() {{
                if (newWorker.state === "installed" && navigator.serviceWorker.controller) {{
                  // Emit a custom event that the React app can listen to
                  window.dispatchEvent(new CustomEvent("sw:update-available", {{
                    detail: {{ registration: reg }}
                  }}));
                }}
              }});
            }});
          }})
          .catch(function(err) {{
            console.warn("[{cfg.app_name}] Service worker registration failed:", err);
          }});
      }});
    }})();
    </script>
    <link rel="manifest" href="/manifest.webmanifest" />
    <meta name="theme-color" content="{cfg.theme_color}" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />
    <meta name="apple-mobile-web-app-title" content="{cfg.app_short_name}" />
    """)


