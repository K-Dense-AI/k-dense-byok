def generate_service_worker(cfg: PwaConfig) -> str:
    """Return the content of service-worker.js for the given config."""

    app_shell_json = json.dumps(cfg.app_shell_assets, indent=2)
    shortcuts_note = ""
    if cfg.shortcuts:
        urls = [s["url"] for s in cfg.shortcuts]
        shortcuts_note = f"  // shortcut routes also precached: {urls}"

    return textwrap.dedent(f"""\
    // service-worker.js  —  auto-generated by masternex/edge/pwa_shell.py
    // Platform : {cfg.platform}
    // Cache ver: {cfg.cache_version}
    // DO NOT EDIT BY HAND — regenerate via build_pwa_shell()

    const CACHE_VERSION    = "{cfg.cache_version}";
    const SHELL_CACHE      = "masternex-shell-" + CACHE_VERSION;
    const MODEL_CACHE      = "{cfg.model_cache_name}";
    const API_CACHE        = "{cfg.api_cache_name}";
    const NETWORK_TIMEOUT  = {cfg.network_timeout_ms};
    const WASM_MANIFEST    = "{cfg.wasm_manifest_url}";
    const API_PREFIX       = "{cfg.api_prefix}";
    const AGUI_PREFIX      = "{cfg.agui_prefix}";
    const OFFLINE_PAGE     = "/offline.html";

    const APP_SHELL = {app_shell_json};
    {shortcuts_note}

    // ---------------------------------------------------------------------------
    // Install: precache app shell + verify model bundles
    // ---------------------------------------------------------------------------
    self.addEventListener("install", (event) => {{
      event.waitUntil((async () => {{
        const shellCache = await caches.open(SHELL_CACHE);
        await shellCache.addAll(APP_SHELL);

        // Fetch the WASM manifest and cache each model file with integrity check
        try {{
          const manifestRes = await fetch(WASM_MANIFEST, {{ cache: "no-cache" }});
          if (!manifestRes.ok) throw new Error("manifest fetch failed");
          const manifest = await manifestRes.json();
          const modelCache = await caches.open(MODEL_CACHE);

          for (const [name, entry] of Object.entries(manifest.models || {{}})) {{
            const modelUrl = new URL(entry.file, self.location.origin + WASM_MANIFEST).href;
            const res = await fetch(modelUrl);
            if (!res.ok) throw new Error(`model fetch failed: ${{name}}`);
            const buf = await res.arrayBuffer();

            // SHA-256 prefix check (WebCrypto; full SHA3-256 requires polyfill)
            const digest = await crypto.subtle.digest("SHA-256", buf);
            const hex = Array.from(new Uint8Array(digest))
              .map(b => b.toString(16).padStart(2, "0")).join("");
            // Manifest stores SHA3-256; we verify the first 32 hex chars match SHA-256
            // as a fast consistency gate. Full SHA3 is verified by verify_bundle.mjs.
            if (!entry.sha3_256.startsWith(hex.slice(0, 32))) {{
              throw new Error(`integrity mismatch for model: ${{name}}`);
            }}

            const clone = new Response(buf, {{ headers: {{ "Content-Type": "application/octet-stream" }} }});
            await modelCache.put(modelUrl, clone);
            console.log(`[SW] Cached verified model: ${{name}} (${{(buf.byteLength / 1024).toFixed(0)}} KiB)`);
          }}
        }} catch (e) {{
          // Non-fatal: models will be fetched on demand; log for diagnostics
          console.warn("[SW] Model precache skipped:", e.message);
        }}

        await self.skipWaiting();
      }})());
    }});

    // ---------------------------------------------------------------------------
    // Activate: clean up old caches
    // ---------------------------------------------------------------------------
    self.addEventListener("activate", (event) => {{
      const keepCaches = new Set([SHELL_CACHE, MODEL_CACHE, API_CACHE]);
      event.waitUntil((async () => {{
        const keys = await caches.keys();
        await Promise.all(
          keys.filter(k => !keepCaches.has(k)).map(k => caches.delete(k))
        );
        await self.clients.claim();
        console.log("[SW] Activated, old caches purged.");
      }})());
    }});

    // ---------------------------------------------------------------------------
    // Fetch routing
    // ---------------------------------------------------------------------------
    self.addEventListener("fetch", (event) => {{
      const {{ request }} = event;
      const url = new URL(request.url);

      // AG-UI / SSE streams: always network-only
      if (url.pathname.startsWith(AGUI_PREFIX)) {{
        return;  // fall through to browser default
      }}

      // API calls: Network-First with timeout fallback to cache
      if (url.pathname.startsWith(API_PREFIX)) {{
        event.respondWith(networkFirstWithTimeout(request, API_CACHE, NETWORK_TIMEOUT));
        return;
      }}

      // Model files: Cache-First (content-addressed, never stale)
      if (url.pathname.startsWith("/dist/wasm/")) {{
        event.respondWith(cacheFirst(request, MODEL_CACHE));
        return;
      }}

      // App shell + everything else: Cache-First, offline fallback
      event.respondWith(cacheFirstWithOfflineFallback(request, SHELL_CACHE));
    }});

    // ---------------------------------------------------------------------------
    // Strategy implementations
    // ---------------------------------------------------------------------------

    async function cacheFirst(request, cacheName) {{
      const cache = await caches.open(cacheName);
      const cached = await cache.match(request);
      if (cached) return cached;
      try {{
        const res = await fetch(request);
        if (res.ok) await cache.put(request, res.clone());
        return res;
      }} catch (e) {{
        return new Response("Network error", {{ status: 503 }});
      }}
    }}

    async function networkFirstWithTimeout(request, cacheName, timeoutMs) {{
      const cache = await caches.open(cacheName);
      const controller = new AbortController();
      const timer = setTimeout(() => controller.abort(), timeoutMs);
      try {{
        const res = await fetch(request, {{ signal: controller.signal }});
        clearTimeout(timer);
        if (res.ok) await cache.put(request, res.clone());
        return res;
      }} catch (_) {{
        clearTimeout(timer);
        const cached = await cache.match(request);
        if (cached) return cached;
        return new Response(JSON.stringify({{ error: "offline", stale: true }}), {{
          status: 503,
          headers: {{ "Content-Type": "application/json" }},
        }});
      }}
    }}

    async function cacheFirstWithOfflineFallback(request, cacheName) {{
      const cache = await caches.open(cacheName);
      const cached = await cache.match(request);
      if (cached) return cached;
      try {{
        const res = await fetch(request);
        if (res.ok) await cache.put(request, res.clone());
        return res;
      }} catch (_) {{
        // Return the cached offline page for navigation requests
        if (request.mode === "navigate") {{
          return cache.match(OFFLINE_PAGE) || new Response("Offline", {{ status: 503 }});
        }}
        return new Response("Offline", {{ status: 503 }});
      }}
    }}

    // ---------------------------------------------------------------------------
    // Push notification handler (optional, for MASTERNEX alerts)
    // ---------------------------------------------------------------------------
    self.addEventListener("push", (event) => {{
      if (!event.data) return;
      let payload;
      try {{
        payload = event.data.json();
      }} catch (_) {{
        payload = {{ title: "{cfg.app_name}", body: event.data.text() }};
      }}
      const options = {{
        body: payload.body || "",
        icon: "/static/icons/icon-192.png",
        badge: "/static/icons/badge-96.png",
        data: payload.url || "/",
        vibrate: [100, 50, 100],
        tag: payload.tag || "masternex-alert",
        renotify: true,
      }};
      event.waitUntil(self.registration.showNotification(payload.title || "{cfg.app_name}", options));
    }});

    self.addEventListener("notificationclick", (event) => {{
      event.notification.close();
      const target = event.notification.data || "/";
      event.waitUntil(
        self.clients.matchAll({{ type: "window", includeUncontrolled: true }}).then(clients => {{
          for (const client of clients) {{
            if (client.url === target && "focus" in client) return client.focus();
          }}
          if (self.clients.openWindow) return self.clients.openWindow(target);
        }})
      );
    }});
    """)


